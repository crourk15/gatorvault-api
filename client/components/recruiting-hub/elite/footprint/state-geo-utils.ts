type GeoFeature = {
  rsmKey: string;
  properties?: { name?: string; postal?: string; st?: string };
};

export function stateCodeFromGeo(geo: GeoFeature): string | null {
  const postal = geo.properties?.postal || geo.properties?.st;
  if (postal && postal.length === 2) return postal.toUpperCase();
  const name = geo.properties?.name;
  if (name && STATE_NAME_TO_CODE[name]) return STATE_NAME_TO_CODE[name];
  return null;
}

