const fs = require('fs');
const path = require('path');

const target = path.join(__dirname, '../lib/staff-note-picker.js');
const lines = [
  '/**',
  ' * Pick the best staff/scouting note for a player — rejects beat-article bleed.',
  ' */',
  'function escapeReg(s) {',
  "  return String(s).replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&');",
  '}',
  '',
  'function normalizePlayerTokens(name) {',
  '  const parts = String(name || "").trim().split(/\\s+/).filter(Boolean);',
  '  return {',
  '    full: parts.join(" ").toLowerCase(),',
  '    last: (parts[parts.length - 1] || "").toLowerCase(),',
  '  };',
  '}',
  '',
  'function scrubNotePrefix(text) {',
  '  return String(text || "")',
  '    .replace(/^Reports View All Reports[^\\w]*/i, "")',
  '    .replace(/\\s+/g, " ")',
  '    .trim();',
  '}',
  '',
  'function mentionsPlayer(text, tokens) {',
  '  const t = String(text || "").toLowerCase();',
  '  if (tokens.full && t.includes(tokens.full)) return true;',
  '  if (tokens.last.length >= 4 && new RegExp(`\\\\b${escapeReg(tokens.last)}\\\\b`, "i").test(t)) return true;',
  '  return false;',
  '}',
  '',
  'function scoreNoteCandidate(text, playerName) {',
  '  const cleaned = scrubNotePrefix(text);',
  '  if (!cleaned || cleaned.length < 24) return -100;',
  '  const tokens = normalizePlayerTokens(playerName);',
  '  let score = 0;',
  '  if (mentionsPlayer(cleaned, tokens)) score += 12;',
  '  else score -= 18;',
  '  if (/scouting summary/i.test(cleaned)) score += 8;',
  '  if (/hard commit/i.test(cleaned) && !mentionsPlayer(cleaned, tokens)) score -= 25;',
  '  if (/official visit season/i.test(cleaned) && !mentionsPlayer(cleaned, tokens)) score -= 15;',
  '  const otherNames = cleaned.match(/\\b[A-Z][a-z]+\\s+[A-Z][a-z]+\\b/g) || [];',
  '  for (const nm of otherNames) {',
  '    const lower = nm.toLowerCase();',
  '    if (lower !== tokens.full && !lower.includes(tokens.last)) score -= 8;',
  '  }',
  '  return score;',
  '}',
  '',
  'function pickStaffNoteText(breakdown) {',
  '  if (!breakdown) return "";',
  '  const candidates = [];',
  '  for (const field of ["staffNotes", "projection", "recruitingStory", "insiderNotes"]) {',
  '    const v = breakdown[field];',
  '    if (typeof v === "string" && v.trim()) candidates.push(v.trim());',
  '  }',
  '  if (Array.isArray(breakdown.strengths)) {',
  '    for (const s of breakdown.strengths) {',
  '      if (typeof s === "string" && s.trim()) candidates.push(s.trim());',
  '    }',
  '  }',
  '  let best = "";',
  '  let bestScore = -Infinity;',
  '  for (const c of candidates) {',
  '    const s = scoreNoteCandidate(c, breakdown.playerName);',
  '    if (s > bestScore) {',
  '      bestScore = s;',
  '      best = scrubNotePrefix(c);',
  '    }',
  '  }',
  '  return bestScore >= 4 ? best : "";',
  '}',
  '',
  'module.exports = { pickStaffNoteText, scoreNoteCandidate, scrubNotePrefix, mentionsPlayer };',
  '',
];

fs.writeFileSync(target, lines.join('\n'), 'utf8');
console.log('wrote', target);
